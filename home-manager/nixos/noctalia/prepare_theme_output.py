"""Prepare Noctalia's writable theme outputs without modifying any link target."""

import argparse
import json
import os
from pathlib import Path
import stat
import tempfile


PLACEHOLDER = "# Runtime colors are generated by Noctalia's built-in Ghostty template.\n"


def prepare(theme, backup, placeholder=PLACEHOLDER):
    # Never create/replace files through a parent directory linked into the store.
    parent = theme.parent.resolve()
    if parent.is_relative_to("/nix/store"):
        raise ValueError("Theme output directory resolves into the Nix store")
    theme.parent.mkdir(parents=True, exist_ok=True)
    exists = theme.exists() or theme.is_symlink()
    if exists:
        if not theme.is_file():
            raise ValueError("Existing Noctalia theme is not a readable regular file")
        metadata = theme.lstat()
        if (not theme.is_symlink() and metadata.st_nlink == 1
                and metadata.st_uid == os.getuid() and metadata.st_mode & stat.S_IWUSR):
            return False  # Already a private writable output; preserve generated data.
        contents = theme.read_bytes()
        backup.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        try:
            fd = os.open(backup, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        except FileExistsError:
            pass  # Preserve the original backup on repeated activations.
        else:
            with os.fdopen(fd, "wb") as output:
                output.write(contents)
    else:
        contents = placeholder.encode()

    # Atomic replacement detaches a symlink/hardlink instead of chmod'ing or
    # truncating its target. It also makes old mode-0444 local files writable.
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=theme.parent, delete=False) as output:
            temporary = Path(output.name)
            output.write(contents)
        temporary.chmod(0o644)
        os.replace(temporary, theme)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    return True


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest",
        type=Path,
        help="JSON list of {theme, backup, placeholder?} entries prepared in one process",
    )
    parser.add_argument("theme", type=Path, nargs="?")
    parser.add_argument("backup", type=Path, nargs="?")
    parser.add_argument("--placeholder", default=PLACEHOLDER)
    args = parser.parse_args()

    if args.manifest is not None:
        entries = []
        for entry in json.loads(args.manifest.read_text()):
            # A missing placeholder key and a null one both mean "use the default".
            placeholder = entry.get("placeholder")
            entries.append(
                (Path(entry["theme"]), Path(entry["backup"]),
                 PLACEHOLDER if placeholder is None else placeholder)
            )
    elif args.theme is not None and args.backup is not None:
        entries = [(args.theme, args.backup, args.placeholder)]
    else:
        parser.error("provide --manifest, or both theme and backup")

    # One interpreter serves every entry: per-app activation entries made the
    # boot-time cost of this preparer grow with the number of apps.
    for theme, backup, placeholder in entries:
        if prepare(theme, backup, placeholder):
            print(f"Prepared writable Noctalia theme output: {theme}")
